/** Replays prior turns to the model, re-attaching the control tags it used. */
function toModelHistory(
  messages: InterviewMessage[],
  answer: string,
): ChatMessage[] {
  const history: ChatMessage[] = [];
  for (const m of messages) {
    if (m.role === MessageRole.CANDIDATE) {
      history.push({ role: 'user', content: m.content });
    } else if (m.role === MessageRole.INTERVIEWER) {
      const meta = readInterviewerMeta(m.metadata);
      const tag = meta ? `${tagFor(KIND_TO_ACTION[meta.kind])} ` : '';
      history.push({ role: 'assistant', content: `${tag}${m.content}` });
    }
  }
  history.push({ role: 'user', content: answer });
  return history.slice(-HISTORY_MESSAGES);
}

function findSavedTurn(messages: InterviewMessage[], clientMessageId: string) {
  const index = messages.findIndex(
    (m) =>
      m.role === MessageRole.CANDIDATE &&
      (m.metadata as CandidateMeta | null)?.clientMessageId === clientMessageId,
  );
  if (index === -1) return null;
  const interviewer = messages
    .slice(index + 1)
    .find((m) => m.role === MessageRole.INTERVIEWER);
  return interviewer ? { candidate: messages[index], interviewer } : null;
}

/**
 * Time actually spent: from start to the last recorded activity, so leaving
 * a tab open for a day does not count as a day of practice.
 */
function activeDurationSecs(interview: InterviewWithTranscript): number {
  if (!interview.startedAt) return 0;
  const activity = [
    ...interview.messages.map((m) => m.createdAt.getTime()),
    ...interview.codingSubs.map((s) => s.createdAt.getTime()),
  ];
  const last = activity.length > 0 ? Math.max(...activity) : 0;
  return Math.max(0, Math.floor((last - interview.startedAt.getTime()) / 1000));
}

function describeCoding(submissions: CodingSubmission[]): string | null {
  if (submissions.length === 0) return null;
  const byProblem = new Map<string, CodingSubmission[]>();
  for (const s of submissions) {
    byProblem.set(s.problemId, [...(byProblem.get(s.problemId) ?? []), s]);
  }
  return [...byProblem.values()]
    .map((attempts) => {
      const best = attempts.reduce((a, b) =>
        b.testsTotal > 0 &&
        b.testsPassed / b.testsTotal >=
          a.testsPassed / Math.max(a.testsTotal, 1)
          ? b
          : a,
      );
      const hints = Math.max(...attempts.map((a) => a.hintsUsed));
      return `- ${best.problemTitle} (${best.difficulty}, ${best.language}): best run passed ${best.testsPassed}/${best.testsTotal} tests over ${attempts.length} attempt(s), ${hints} hint(s) used`;
    })
    .join('\n');
}
